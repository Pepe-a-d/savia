const cache = new Map();

/** Devuelve un canvas con el mapa pintado a `scale` píxeles por punto. */
export function bitmap(map, color, detail, scale = 1) {
  const key = `${map.join('')}|${color}|${detail}|${scale}`;
  if (cache.has(key)) return cache.get(key);
  const h = map.length;
  const w = map[0].length;
  const c = document.createElement('canvas');
  c.width = w * scale;
  c.height = h * scale;
  const g = c.getContext('2d');
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = map[y][x];
      if (ch === '.') continue;
      g.fillStyle = ch === '#' ? color : detail;
      g.fillRect(x * scale, y * scale, scale, scale);
    }
  }
  cache.set(key, c);
  return c;
}

const urlCache = new Map();
function toURL(canvas) {
  if (!urlCache.has(canvas)) urlCache.set(canvas, canvas.toDataURL());
  return urlCache.get(canvas);
}

export function iconURL(name, color, detail = PAL.creamHi) {
  return toURL(bitmap(ICON_MAPS[name] || ICON_MAPS.semilla, color, detail, 1));
}

export function resURL(cur) {
  const [c, d] = RES_COLORS[cur] || RES_COLORS.f;
  return toURL(bitmap(RES_MAPS[cur] || RES_MAPS.f, c, d, 1));
}

/** Valor CSS de cursor ('arrow' o 'hand'): imagen pixel a 2× con su punto caliente. */
export function cursorCSS(kind) {
  const map = CURSOR_MAPS[kind];
  const S = 2;
  const c = document.createElement('canvas');
  c.width = map[0].length * S;
  c.height = map.length * S;
  const g = c.getContext('2d');
  const col = { X: PAL.ink, o: PAL.cream, h: PAL.creamHi };
  map.forEach((row, y) => [...row].forEach((ch, x) => {
    if (!col[ch]) return;
    g.fillStyle = col[ch];
    g.fillRect(x * S, y * S, S, S);
  }));
  const [hx, hy] = kind === 'hand' ? [10, 1] : [1, 1];
  return `url(${c.toDataURL()}) ${hx} ${hy}, ${kind === 'hand' ? 'pointer' : 'auto'}`;
}

