const cache = new Map();

/** Devuelve un canvas con el mapa pintado a `scale` píxeles por punto. */
export function bitmap(map, color, detail, scale = 1) {
  const key = `${map.join('')}|${color}|${detail}|${scale}`;
  if (cache.has(key)) return cache.get(key);
  const h = map.length;
  const w = map[0].length;
  const c = document.createElement('canvas');
  c.width = w * scale;
  c.height = h * scale;
  const g = c.getContext('2d');
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = map[y][x];
      if (ch === '.') continue;
      g.fillStyle = ch === '#' ? color : detail;
      g.fillRect(x * scale, y * scale, scale, scale);
    }
  }
  cache.set(key, c);
  return c;
}

const urlCache = new Map();
function toURL(canvas) {
  if (!urlCache.has(canvas)) urlCache.set(canvas, canvas.toDataURL());
  return urlCache.get(canvas);
}

export function iconURL(name, color, detail = PAL.hyphaHi) {
  return toURL(bitmap(ICON_MAPS[name] || ICON_MAPS.espora, color, detail, 1));
}

export function resURL(cur) {
  const colors = { n: [PAL.n, PAL.big], m: [PAL.m, '#BDF2FF'], a: [PAL.a, '#FFF1B3'], e: [PAL.e, '#FFE0F0'], t: ['#B6E35A', '#3E5A2A'], c: ['#C79BFF', '#F4E6FF'] };
  const [c, d] = colors[cur];
  return toURL(bitmap(RES_MAPS[cur], c, d, 1));
}

